public class Escape {
    public static void main(String[] args){
        System.out.println("Good Day \\everyone\\ "); // for insert a backslash in text at this point
        System.out.println("Good Day\t everyone ");  // insert a tab in text at this point
        System.out.println("Good Day \beveryone ");  // insert a backspace in text
        System.out.println("Good Day\" everyone\" "); //inset a double quote in text
        System.out.println("Good Day \neveryone\n ");  //insert a newline
        System.out.println("Good Day \'everyone\' "); // insert a single quote
    }
}


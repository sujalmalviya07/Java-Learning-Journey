public class SwapNumber {
    public static void main(String[] args){
        System.out.println("Swaping program......");
        int num1 =10;
        System.out.println("Number A is : "+num1 );
        int num2 =11;
        System.out.println("Number B is : "+num2 );
        int tem = num1;
        num1 = num2;
        num2=tem;
        System.out.println("After Swaping ...");
        System.out.println("Number A is : "+num1 );
        System.out.println("Number B is : "+num2 );

    }
}
